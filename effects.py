def build_apo_config(effect: EffectPreset | None, device_guid: str | None = None) -> str:
    """把 EffectPreset 转成 Equalizer APO 配置文本"""
    lines = [
        "# Generated by AudioEnhancer",
        "# 退出 AudioEnhancer 后此文件会被清空，恢复默认音质",
        "",
        "Preamp: 0 dB",
        "",
    ]
    if effect is None:
        return "\n".join(lines)

    # 写入当前生效音效标记，便于启动读回
    lines.insert(2, f"# ActiveEffect: {effect.key}")
    lines[4] = f"Preamp: {effect.preamp} dB"
    if device_guid:
        lines.insert(4, f"Device: {device_guid}")

    # 参数化 EQ（Peak filter）
    for freq, gain, q in effect.peq:
        lines.append(f"Filter: ON PK Fc {freq} Hz Gain {gain} dB Q {q}")

    # 低频搁架（低音增强）
    if effect.bass_boost:
        freq, gain = effect.bass_boost
        lines.append(f"Filter: ON LSC Fc {freq} Hz Gain {gain} dB Q 0.7")

    # 高频搁架（人声/HIFI）
    if effect.treble_boost:
        freq, gain = effect.treble_boost
        lines.append(f"Filter: ON HSC Fc {freq} Hz Gain {gain} dB Q 0.7")

    # 3D/环绕：简单的交叉馈送 + 延时
    if effect.surround_level > 0:
        mix = int(effect.surround_level * 100)
        cross = effect.surround_level
        direct = 1.0 - cross
        lines.append(f"# Crossfeed for surround ({mix}%)")
        lines.append(f"Copy: L={direct:.2f}*L+{cross:.2f}*R R={cross:.2f}*L+{direct:.2f}*R")

    # 声道延时（毫秒）
    if effect.channel_delay[1] > 0:
        delay_ms = effect.channel_delay[1]
        lines.extend(["Channel: R", f"Delay: {delay_ms} ms", "Channel: all"])

    lines.append("")
    return "\n".join(lines)


def normalize_effect_key(key: str | None) -> str:
    """将旧版预设选择映射到仍在界面中的预设。"""
    return {"3d": "surround360"}.get(key or "", key or "")


def get_effect_by_key(key: str) -> EffectPreset | None:
    key = normalize_effect_key(key)
    for e in EFFECTS:
        if e.key == key:
            return e
    return None
