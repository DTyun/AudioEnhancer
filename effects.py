from dataclasses import dataclass, field
from typing import List, Tuple


@dataclass
class EffectPreset:
    key: str
    name: str
    subtitle: str
    icon: str = "🎵"
    # 参数化均衡器: (频率 Hz, 增益 dB, Q 值)
    peq: List[Tuple[float, float, float]] = field(default_factory=list)
    # 低音增强: (截止频率 Hz, 增益 dB)
    bass_boost: Tuple[float, float] | None = None
    # 高频增强: (截止频率 Hz, 增益 dB)
    treble_boost: Tuple[float, float] | None = None
    # 3D/环绕强度 0-1
    surround_level: float = 0.0
    # 前置放大 dB
    preamp: float = 0.0
    # 声道延时 ms（模拟环绕/3D）
    channel_delay: Tuple[float, float] = (0.0, 0.0)


